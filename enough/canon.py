def _kept_file(target: Path, project_dir: Path | None = None) -> str | None:
    """Which enough-kept file ``target`` is, or None: ``"catalog"`` (a
    volume's ``canon.cosm``), ``"project-catalog"`` (``rness/canon.cosm``),
    ``"meta"`` (``.canon.json`` / ``.cachebox.json``, by name anywhere), or
    ``"mirror"`` (``_cachebox.merirmaid`` or a ``modality: mirror``
    ``.merirmaid`` under the store)."""
    try:
        real = target.resolve(strict=False)
    except OSError:
        return None
    if real.name in (META_NAME, LEGACY_META_NAME):
        return "meta"
    if project_dir is not None:
        try:
            if real == (Path(project_dir) / PROJECT_CATALOG).resolve(strict=False):
                return "project-catalog"
        except OSError:
            pass
    try:
        store = root().resolve(strict=False)
        rel = real.relative_to(store)
    except (OSError, ValueError):
        return None
    if len(rel.parts) == 2 and rel.parts[1] == CATALOG_NAME:
        return "catalog"
    if real.name == LEGACY_MIRROR_NAME:
        return "mirror"
    if real.suffix == ".merirmaid" and real.is_file() and _is_mirror_text(real):
        return "mirror"
    return None


def is_catalog_file(target: Path, project_dir: Path | None = None) -> bool:
    """True iff ``target`` is a file enough keeps and nobody else writes: a
    volume's ``canon.cosm``, the project's ``rness/canon.cosm`` (when
    ``project_dir`` is given), a volume's metadata json, or a generated
    mirror under the store (also by ``modality: mirror`` frontmatter). Used
    by the write guards in tools.py / server.py."""
    return _kept_file(target, project_dir) is not None


_DENIAL_DETAIL = {
    "catalog": ("canon.cosm is the volume's catalog: enough regenerates it from the volume's "
                "files on every change, so an edit here would be overwritten. add, move or "
                "remove files with the canon transfer/ingest ops."),
    "project-catalog": ("rness/canon.cosm is this project's catalog: enough rewrites it when "
                        "the project's files are added, removed or renamed."),
    "meta": "a volume's metadata (.canon.json) is owned by enough: origin, ingest status, fingerprint.",
    "mirror": ("this is a generated diagram (modality: mirror) of a canon volume, drawn from its "
               "files; it is never edited directly."),
}


def catalog_write_denial(target: Path, project_dir: Path | None = None) -> str | None:
    """Denial message if ``target`` is a file enough keeps (see
    `is_catalog_file`), else None. The guard both the agent's
    ``write_file`` and ``POST /api/file`` apply."""
    what = _kept_file(target, project_dir)
    if what is None:
        return None
    return f"error: {CATALOG_DENIAL}. {_DENIAL_DETAIL[what]}"


