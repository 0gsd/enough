def volume_summary(name: str) -> dict[str, Any]:
    """Metadata + live stats for one volume (the listing row shape)."""
    box = _require_volume(name)
    meta = load_meta(name)
    stats = _stats(box)
    return {
        "name": name,
        "origin": meta.get("origin"),
        "status": meta.get("status", "complete"),
        "created_at": meta.get("created_at"),
        "updated_at": meta.get("updated_at"),
        "item_count": stats["item_count"],
        "dir_count": stats["dir_count"],
        "total_size": stats["total_size"],
        "total_size_human": _sizeof_human(stats["total_size"]),
        "ingest": meta.get("ingest"),
        "catalog": CATALOG_NAME,
        "holotype": (box / HOLOTYPE_NAME).is_file(),
    }


def list_volumes() -> list[dict[str, Any]]:
    """Every volume (root-level folder in the store), summarized, sorted
    by name."""
    r = root()
    out: list[dict[str, Any]] = []
    for entry in sorted(r.iterdir(), key=lambda p: p.name.lower()):
        if not entry.is_dir() or entry.name.startswith("."):
            continue
        try:
            out.append(volume_summary(entry.name))
        except CanonError:
            continue
    return out


def volume_tree(name: str) -> dict[str, Any]:
    """Full nested tree of a volume for the icon grid, plus its summary."""
    _require_volume(name)
    summary = volume_summary(name)
    summary["tree"] = _scan_tree(volume_dir(name))
    return summary


def create_volume(name: str, *, origin: dict[str, Any] | None = None,
                  status: str = "complete") -> dict[str, Any]:
    """Create an empty volume. Errors if one already exists."""
    name = _validate_name(name)
    box = volume_dir(name)
    if box.exists():
        raise CanonError(f"a volume named {name!r} already exists.")
    box.mkdir(parents=True, exist_ok=False)
    meta = _default_meta(name)
    if origin:
        meta["origin"] = origin
    meta["status"] = status
    save_meta(name, meta)
    regenerate_catalog(name)
    return volume_summary(name)


def rename_volume(name: str, new_name: str) -> dict[str, Any]:
    src = _require_volume(name)
    new_name = _validate_name(new_name)
    dst = volume_dir(new_name)
    if dst.exists():
        raise CanonError(f"a volume named {new_name!r} already exists.")
    src.rename(dst)
    meta = load_meta(new_name)
    meta["name"] = new_name
    save_meta(new_name, meta)
    regenerate_catalog(new_name)
    return volume_summary(new_name)


def delete_volume(name: str, *, confirm: bool) -> dict[str, Any]:
    """Delete a volume and everything in it. Deliberate: requires an
    explicit confirm flag (the no-deletes-without-confirmation discipline)."""
    box = _require_volume(name)
    if not confirm:
        raise CanonError(
            f"deleting the {name!r} volume removes it and all its contents "
            f"permanently. this is not reversible from here. re-issue the "
            f"delete with confirmation once the user has agreed in their own "
            f"words."
        )
    shutil.rmtree(box)
    return {"deleted": name}


