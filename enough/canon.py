"""canon — enough's library: the machine-global store at ``~/enough/canon/``.

Canon was called Cacheawl until 0.4.3; ``enough/cacheawl.py`` is now a
one-release shim that re-exports this module under the old names.

A **volume** (was: cachebox) is a ROOT-LEVEL folder inside the store. Only
direct children of the store are volumes; folders nested deeper are plain
folders. A volume holds files the user wants to keep plus two
backend-owned sidecars:

- ``canon.cosm``   — the volume's catalog: the ``canon/1`` MiniCOSM
                     (docs/MACROCOSM_OES.md §18.3) enumerating its folders,
                     files and saved articles, and what has been derived
                     from each (markdown twin, EMF twin, atem). Visible in
                     listings, write-refused, regenerated by `reconcile` /
                     `regenerate_catalog` on every mutation the backend
                     makes and on fingerprint drift. Byte-stable: written
                     only when its bytes change, and its only timestamps
                     are the volume's ``created``/``updated`` from meta.
- ``.canon.json``  — hidden metadata (origin request, status, timestamps, a
                     cheap tree fingerprint used by the reconcile check).
                     Never shown in trees.

The merirmaid mirror of a volume (📦/📁/📄, depth-capped, a metadata node)
is no longer persisted: `build_mirror` draws it on demand. The first
reconcile of a volume made before 0.4.3 renames ``.cachebox.json`` to
``.canon.json`` and deletes the old ``_cachebox.merirmaid`` when (and only
when) it is a generated mirror.

A project gets the same enumeration as ``rness/canon.cosm`` (``scope:
project``): what the sidebar shows minus ``rness/``, structure only — no
sizes, no times, no twin states — so a project under git sees no churn from
ordinary edits (`project_catalog`).

Some volumes are plain folders; others are "cached replicas" ingested from
a source (a local path, a website URL, or a set of wikisink articles) to a
user-chosen depth.

The root is resolvable via ``ENOUGH_CANON_ROOT`` (a test/dev hook, mirroring
the ``ENOUGH_WIKISINK_CONFIG`` precedent); the old ``ENOUGH_CACHEAWL_ROOT``
is honoured when the new one is unset, so suites never touch the real
``~/enough/canon``. Without either, the first `root()` call renames an old
``~/enough/cacheawl/`` to ``~/enough/canon/`` when only the old one exists.

Path-traversal safety: every path that crosses the store boundary is
``.resolve()``d and verified to sit under its declared root before any
filesystem op — the same ``/var`` vs ``/private/var`` discipline
``cloud.pipeline_run()`` uses.

No derivation happens here: imports, ingests, listings and reconciles never
call a model (plan §0). EMF twins and atems are made on request elsewhere;
this module only finds them, pairs them with their texts and reports them.
"""

