def _normalize_depth(depth: Any, all_flag: bool, *, source_type: str) -> int | str:
    """Return an int 1..3 or the string 'all'. wikisink rejects 'all'."""
    if all_flag:
        if source_type == "wikisink":
            raise CanonError(
                "the 'all' depth is invalid for a wikisink ingest — crosslink "
                "expansion is unbounded and would pull in most of the "
                "encyclopedia. pick a depth of 1, 2, or 3."
            )
        return "all"
    try:
        d = int(depth)
    except (TypeError, ValueError):
        raise CanonError(
            f"depth must be an integer 1-3 (or set the 'all' flag), got "
            f"{depth!r}."
        ) from None
    if d < 1 or d > 3:
        raise CanonError(f"depth must be 1, 2, or 3 (got {d}); or use 'all'.")
    return d


def _set_progress(name: str, **fields: Any) -> None:
    meta = load_meta(name)
    prog = dict(meta.get("ingest") or {})
    prog.update(fields)
    meta["ingest"] = prog
    save_meta(name, meta)


def ingest_status(name: str) -> dict[str, Any]:
    """Pollable status for an ingest (or a plain volume). Shape the UI polls."""
    meta = load_meta(name)
    return {
        "name": name,
        "status": meta.get("status", "complete"),
        "origin": meta.get("origin"),
        "ingest": meta.get("ingest"),
        "updated_at": meta.get("updated_at"),
    }


def register_ingest(*, box: str, source_type: str, value: str,
                    depth: Any = 1, all_flag: bool = False) -> dict[str, Any]:
    """Register a volume with status 'ingesting' BEFORE the (possibly
    long-running) ingest starts, so ``ingest_status`` is pollable
    immediately and there is never a window where the volume doesn't exist.
    Validates input; raises `CanonError` on a bad request or a volume that's
    already populated. Returns the origin dict."""
    name = _validate_name(box)
    source_type = (source_type or "").strip().lower()
    if source_type not in ("path", "url", "wikisink"):
        raise CanonError(
            f"unknown ingest source type {source_type!r} — use 'path', 'url', "
            f"or 'wikisink'.")
    value = (value or "").strip()
    if not value:
        raise CanonError("an ingest needs a non-empty value (the source).")
    norm_depth = _normalize_depth(depth, all_flag, source_type=source_type)
    d = volume_dir(name)
    if d.is_dir():
        meta = load_meta(name)
        if meta.get("status") == "complete" and _stats(d)["item_count"] > 0:
            raise CanonError(
                f"volume {name!r} already exists and is populated — ingest "
                f"into a fresh volume name, or delete it first if you mean to "
                f"replace it.")
    else:
        d.mkdir(parents=True, exist_ok=False)
        meta = _default_meta(name)
    origin = {"type": source_type, "value": value, "depth": norm_depth}
    meta["origin"] = origin
    meta["status"] = "ingesting"
    meta["ingest"] = {"phase": "queued", "files_written": 0,
                      "started_at": _now_iso(), "error": None}
    save_meta(name, meta)
    regenerate_catalog(name)
    return origin


def run_ingest(project_dir: Path, *, box: str, source_type: str, value: str,
               depth: Any = 1, all_flag: bool = False) -> dict[str, Any]:
    """Run an ingest into the volume ``box``. Registers the volume's
    metadata FIRST with status 'ingesting' (no half-registered volumes),
    then populates it, then marks 'complete'. Any failure marks the volume
    'failed' with the error recorded — a resumable/cleanly-failed state,
    never a phantom complete volume.

    Three source types:
      - ``path``    — copy text files from a local path to ``depth`` folder
                      levels ('all' = unlimited). Skips binaries; never
                      follows symlinks out of the source root; inside a
                      Holotype, leaves out what Comprise keeps outside the
                      model (`_holotype_outside`).
      - ``url``     — crawl same-origin pages to ``depth`` link layers
                      ('all' = subdirectory-scoped, capped), converting each
                      to markdown via the fetch_url plumbing; robots.txt
                      disallow is respected.
      - ``wikisink`` — fuzzy-match an article, save it as a wikisink folder,
                      then expand outlinks ``depth`` crosslink layers.
    """
    name = _validate_name(box)
    source_type = (source_type or "").strip().lower()
    if source_type not in ("path", "url", "wikisink"):
        raise CanonError(
            f"unknown ingest source type {source_type!r} — use 'path', 'url', "
            f"or 'wikisink'."
        )
    value = (value or "").strip()
    if not value:
        raise CanonError("an ingest needs a non-empty value (the source).")
    norm_depth = _normalize_depth(depth, all_flag, source_type=source_type)

    d = volume_dir(name)
    existing = d.is_dir()
    if existing:
        meta = load_meta(name)
        if meta.get("status") == "complete" and _stats(d)["item_count"] > 0:
            raise CanonError(
                f"volume {name!r} already exists and is populated — ingest "
                f"into a fresh volume name, or delete it first if you mean to "
                f"replace it."
            )
    else:
        d.mkdir(parents=True, exist_ok=False)
        meta = _default_meta(name)

    meta["origin"] = {"type": source_type, "value": value, "depth": norm_depth}
    meta["status"] = "ingesting"
    meta["ingest"] = {"phase": "starting", "files_written": 0,
                      "started_at": _now_iso(), "error": None}
    save_meta(name, meta)
    regenerate_catalog(name)

    try:
        if source_type == "path":
            written = _ingest_path(project_dir, name, value, norm_depth)
        elif source_type == "url":
            written = _ingest_url(project_dir, name, value, norm_depth)
        else:
            written = _ingest_wikisink(project_dir, name, value, norm_depth)
    except CanonError:
        _mark_failed(name)
        raise
    except Exception as e:  # noqa: BLE001 — record + re-raise as CanonError
        _mark_failed(name, str(e))
        raise CanonError(f"ingest failed: {e}") from e

    meta = load_meta(name)
    meta["status"] = "complete"
    prog = dict(meta.get("ingest") or {})
    prog.update({"phase": "complete", "files_written": written,
                 "finished_at": _now_iso()})
    meta["ingest"] = prog
    save_meta(name, meta)
    regenerate_catalog(name)
    summary = volume_summary(name)
    summary["files_written"] = written
    return summary


def _mark_failed(name: str, error: str = "") -> None:
    try:
        meta = load_meta(name)
        meta["status"] = "failed"
        prog = dict(meta.get("ingest") or {})
        prog.update({"phase": "failed", "error": error or prog.get("error"),
                     "finished_at": _now_iso()})
        meta["ingest"] = prog
        save_meta(name, meta)
        regenerate_catalog(name)
    except Exception:  # noqa: BLE001 — best effort
        log.exception("could not mark volume %s failed", name)


def _looks_binary(p: Path) -> bool:
    if p.suffix.lower() in _BINARY_EXTS:
        return True
    try:
        with p.open("rb") as f:
            sample = f.read(8192)
    except OSError:
        return True
    return b"\x00" in sample


def looks_binary(p: Path) -> bool:
    """The ingest's binary sniff (a binary extension, else a NUL byte in the first 8 KiB), public for the
    derivation routes (0.4.3, P3), which refuse what an ingest would skip."""
    return _looks_binary(p)


# What a path ingest leaves out of a Holotype's root when the manifest can't
# be read: Comprise's `volume.outside-the-model`, its database, its snapshots
# and the people files (people never leave Comprise).
_HOLOTYPE_OUTSIDE_FALLBACK = (
    frozenset({"people.yaml", "people.proposed.yaml", "store.sqlite", "logo.svg", "logo.png"}),
    frozenset({"feeds", "scans", "bindings", "reports", "snapshots"}),
)
_PEOPLE_GLOB = "people*.yaml"


def _holotype_outside() -> tuple[frozenset[str], frozenset[str]]:
    """``(file names, folder names)`` at a Holotype's root that a path ingest
    skips (plan §6.5): the comprise manifest's ``volume.outside-the-model``
    (entries ending in ``/`` are folders), its ``volume.database``, plus
    ``snapshots/``; ``people*.yaml`` is matched separately by glob."""
    try:
        m = macrocosm.default_registry().get("comprise")
        vol = m.volume if m is not None else None
    except Exception:  # noqa: BLE001 — the fallback is the same list
        vol = None
    if not isinstance(vol, dict) or not isinstance(vol.get("outside-the-model"), list):
        return _HOLOTYPE_OUTSIDE_FALLBACK
    files, dirs = {"people.yaml", "people.proposed.yaml"}, {"snapshots"}
    for entry in vol["outside-the-model"]:
        if isinstance(entry, str) and entry.strip():
            e = entry.strip()
            (dirs if e.endswith("/") else files).add(e.rstrip("/"))
    if isinstance(vol.get("database"), str):
        files.add(vol["database"].strip())
    return frozenset(files), frozenset(dirs)


class HolotypeFilter:
    """What never crosses into Canon from inside a Holotype (plan §6.5, spec
    §18.1): at the root of any folder holding ``holotype.cosm``, the files
    and folders `_holotype_outside` names and any ``people*.yaml``. The one
    rule both ways in apply — a path ingest (`_ingest_path`) and a transfer
    into the store (`transfer`) — so they can never drift apart.

    ``base`` bounds the ancestor search: an entry is private when, for some
    folder between ``base`` and the entry's parent that holds a
    ``holotype.cosm``, the entry's first path step below that folder is a
    private folder, or the entry is a private file directly in it. So a
    source that *is* a private folder, sits inside one, or merely contains a
    Holotype somewhere below is filtered the same way. Root checks are cached
    per instance (one per ingest or transfer)."""

    def __init__(self, base: Path):
        self.base = base
        self.files, self.dirs = _holotype_outside()
        self._roots: dict[Path, bool] = {}

    def _is_root(self, folder: Path) -> bool:
        hit = self._roots.get(folder)
        if hit is None:
            try:
                hit = (folder / HOLOTYPE_NAME).is_file()
            except OSError:
                hit = False
            self._roots[folder] = hit
        return hit

    def private(self, p: Path, is_dir: bool | None = None) -> bool:
        try:
            parts = p.relative_to(self.base).parts
        except ValueError:
            return False
        if not parts:
            return False
        if is_dir is None:
            try:
                is_dir = p.is_dir()
            except OSError:
                is_dir = False
        folder = self.base
        for i, step in enumerate(parts):
            rest = len(parts) - i
            if self._is_root(folder):
                if rest > 1 or is_dir:
                    if step in self.dirs:
                        return True
                elif step in self.files or fnmatch.fnmatch(step, _PEOPLE_GLOB):
                    return True
            folder = folder / step
        return False

    def ignore_for(self, skipped: list[Path]) -> Callable[[str, list[str]], set[str]]:
        """A ``shutil.copytree`` ``ignore`` callable that leaves the private
        entries out and records each one (as a path) in ``skipped``."""
        def ignore(dirpath: str, names: list[str]) -> set[str]:
            out = set()
            for n in names:
                q = Path(dirpath) / n
                if self.private(q):
                    out.add(n)
                    skipped.append(q)
            return out
        return ignore

    def skipped_under(self, folder: Path) -> list[Path]:
        """The private entries a filtered copy of ``folder`` would leave out
        (private folders reported whole, not walked)."""
        found: list[Path] = []
        for cur, dirnames, filenames in os.walk(folder, followlinks=False):
            here = Path(cur)
            keep = []
            for d in sorted(dirnames):
                if self.private(here / d, True):
                    found.append(here / d)
                else:
                    keep.append(d)
            dirnames[:] = keep
            found.extend(here / f for f in sorted(filenames) if self.private(here / f, False))
        return found


def _ingest_path(project_dir: Path, name: str, value: str,
                 depth: int | str) -> int:
    """Copy text files from a local path into the volume, mirroring the
    source structure to ``depth`` folder levels. Never follows symlinks
    out of the source root. A folder holding ``holotype.cosm`` keeps
    Comprise's outside-the-model files and folders, its database and its
    people files out of the copy."""
    src_root = Path(value).expanduser()
    try:
        src_root = src_root.resolve(strict=True)
    except (OSError, RuntimeError):
        raise CanonError(f"source path does not exist: {value!r}.") from None
    if not src_root.is_dir():
        # A single file is a legal source too — unless it is a Holotype's.
        if src_root.is_file():
            if HolotypeFilter(Path(src_root.anchor)).private(src_root, False):
                raise CanonError(_private_refusal(value))
            if _looks_binary(src_root):
                raise CanonError(
                    f"{value!r} looks like a binary file — nothing text to "
                    f"ingest.")
            dest = volume_dir(name) / src_root.name
            shutil.copy2(src_root, dest)
            _set_progress(name, phase="copying", files_written=1)
            return 1
        raise CanonError(f"source path is not a directory or file: {value!r}.")

    box = volume_dir(name)
    written = 0
    unlimited = depth == "all"
    # The ancestor search runs to the filesystem root, so a source that is
    # itself a Holotype's private folder is filtered too.
    holotype = HolotypeFilter(Path(src_root.anchor))
    if holotype.private(src_root, True):
        raise CanonError(_private_refusal(value))
    # ``depth`` counts directory levels to include: depth 1 = files directly
    # in the source root (level 0); depth 2 = one subdir level (0, 1); etc.
    max_levels = None if unlimited else int(depth)
    # os.walk(followlinks=False) never recurses into symlinked directories,
    # so a symlinked subdir can't lead the walk out of the source root.
    for cur, dirnames, filenames in os.walk(src_root, followlinks=False):
        cur_path = Path(cur)
        try:
            rel_dir = cur_path.relative_to(src_root)
        except ValueError:
            continue
        level = 0 if rel_dir == Path(".") else len(rel_dir.parts)
        # Files at this level are copied only when the level is within depth.
        copy_here = max_levels is None or level < max_levels
        if max_levels is not None and level >= max_levels:
            dirnames[:] = []  # nothing deeper is in scope
        # Privacy: people (and Comprise's private stores) never leave
        # Comprise — the walk doesn't even descend into those folders.
        dirnames[:] = [dn for dn in dirnames if not holotype.private(cur_path / dn, True)]
        if not copy_here:
            continue
        for fn in sorted(filenames):
            if holotype.private(cur_path / fn, False):
                continue
            sf = cur_path / fn
            if sf.is_symlink():
                # Skip a file symlink whose target escapes the source root.
                try:
                    if src_root not in sf.resolve().parents:
                        continue
                except OSError:
                    continue
            if _looks_binary(sf):
                continue
            rel = sf.relative_to(src_root)
            dest = box / rel
            dest.parent.mkdir(parents=True, exist_ok=True)
            try:
                shutil.copy2(sf, dest)
                written += 1
            except OSError as e:
                log.warning("canon path ingest skip %s: %s", sf, e)
            if written % 25 == 0:
                _set_progress(name, phase="copying", files_written=written)
            if written >= INGEST_PATH_FILE_CAP:
                _set_progress(name, phase="capped", files_written=written,
                              note=f"hit {INGEST_PATH_FILE_CAP}-file cap")
                return written
    _set_progress(name, phase="copying", files_written=written)
    return written


class _Robots:
    """Thin robots.txt gate for one origin. Fetched through the same broker
    plumbing as page fetches; a missing/unfetchable robots.txt allows all
    (standard behavior)."""

    def __init__(self, origin: str, fetch: Callable[[str], "Any"]):
        self.parser = urllib.robotparser.RobotFileParser()
        self._ok = False
        try:
            res = fetch(origin.rstrip("/") + "/robots.txt")
            if res is not None:
                resp, _used_tor = res
                if resp.status < 400 and resp.text:
                    self.parser.parse(resp.text.splitlines())
                    self._ok = True
        except Exception:  # noqa: BLE001 — absent robots = allow all
            self._ok = False

    def allowed(self, url: str, ua: str = "enough-broker") -> bool:
        if not self._ok:
            return True
        try:
            return self.parser.can_fetch(ua, url)
        except Exception:  # noqa: BLE001
            return True


def _ingest_url(project_dir: Path, name: str, value: str,
                depth: int | str) -> int:
    """Same-origin crawl → markdown files mirroring URL paths. Reuses the
    fetch_url plumbing (allowlist/Tor gating + pandoc) via tools.fetch_gated
    — no parallel HTTP stack."""
    from . import tools as _tools  # late import: avoid import cycle

    parsed = urllib.parse.urlparse(value)
    if parsed.scheme not in ("http", "https") or not parsed.hostname:
        raise CanonError(f"url ingest needs an http(s) URL, got {value!r}.")
    origin = f"{parsed.scheme}://{parsed.netloc}"
    start_dir = posix_dirname(parsed.path)

    def fetch(u: str):
        try:
            return _tools.fetch_gated(project_dir, u)
        except _tools.FetchDenied as e:
            # Toggle off / off-allowlist with no Tor is fatal for a crawl.
            raise CanonError(str(e)) from None
        except _tools.FetchError:
            return None

    robots = _Robots(origin, fetch)
    box = volume_dir(name)
    unlimited = depth == "all"
    max_layers = None if unlimited else int(depth)

    seen: set[str] = set()
    written = 0
    # BFS over (url, layer). layer 1 = start page.
    queue: deque[tuple[str, int]] = deque([(_canonical_url(value), 1)])
    while queue:
        url, layer = queue.popleft()
        if url in seen:
            continue
        seen.add(url)
        if len(seen) > INGEST_URL_PAGE_CAP:
            _set_progress(name, phase="capped", files_written=written,
                          note=f"hit {INGEST_URL_PAGE_CAP}-page cap")
            break
        if not robots.allowed(url):
            continue
        result = fetch(url)
        if result is None:
            continue
        resp, _used_tor = result
        if resp.status >= 400 or "html" not in (resp.content_type or ""):
            # Non-HTML or error: skip crawling, but keep plain text if useful.
            if resp.status < 400 and resp.text and "text/plain" in (resp.content_type or ""):
                written += _write_url_doc(box, url, resp.text, ".txt")
            continue
        md, _ok = _tools._markdownify_via_pandoc(resp.text)
        written += _write_url_doc(box, url, md, ".md")
        _set_progress(name, phase="crawling", files_written=written,
                      pages_seen=len(seen))
        # Enqueue same-origin links for the next layer.
        if max_layers is not None and layer >= max_layers:
            continue
        for link in _extract_links(resp.text, url):
            lp = urllib.parse.urlparse(link)
            if f"{lp.scheme}://{lp.netloc}" != origin:
                continue
            if unlimited and not lp.path.startswith(start_dir):
                continue  # 'all' stays within the starting subdirectory path
            cu = _canonical_url(link)
            if cu not in seen:
                queue.append((cu, layer + 1))
    _set_progress(name, phase="crawling", files_written=written,
                  pages_seen=len(seen))
    return written


def posix_dirname(path: str) -> str:
    import posixpath
    d = posixpath.dirname(path or "/")
    return (d or "/") if d.endswith("/") else d + "/"


def _canonical_url(url: str) -> str:
    """Drop the fragment; keep query. Trailing-slash normalized off."""
    p = urllib.parse.urlparse(url)
    path = p.path or "/"
    return urllib.parse.urlunparse((p.scheme, p.netloc, path, "", p.query, ""))


def _extract_links(html: str, base_url: str) -> list[str]:
    out: list[str] = []
    for m in re.finditer(r'href\s*=\s*["\']([^"\'#]+)["\']', html, re.IGNORECASE):
        href = m.group(1).strip()
        if href.lower().startswith(("mailto:", "javascript:", "data:", "tel:")):
            continue
        out.append(urllib.parse.urljoin(base_url, href))
    return out


def _write_url_doc(box: Path, url: str, text: str, ext: str) -> int:
    """Write one crawled page as a file mirroring its URL path."""
    p = urllib.parse.urlparse(url)
    rel_path = p.path.strip("/")
    if not rel_path:
        rel_path = "index"
    # Sanitize each path segment; keep the directory structure.
    segs = [_slugify(urllib.parse.unquote(s), max_len=60) for s in rel_path.split("/") if s]
    if not segs:
        segs = ["index"]
    # A path ending in a dir (…/foo/) becomes …/foo/index.
    if p.path.endswith("/"):
        segs.append("index")
    if p.query:
        segs[-1] += "-" + _slugify(p.query, max_len=20)
    rel = Path(*segs).with_suffix(ext)
    dest = box / rel
    try:
        dest.relative_to(box.resolve())
    except ValueError:
        dest = box / (segs[-1] + ext)
    dest.parent.mkdir(parents=True, exist_ok=True)
    header = f"<!-- source: {url} -->\n\n"
    dest.write_text(header + (text or ""), encoding="utf-8")
    return 1


def _ingest_wikisink(project_dir: Path, name: str, value: str,
                     depth: int) -> int:
    """Fuzzy-match an article via wikisink search, save it as a folder in
    the volume, then expand outlinks ``depth`` crosslink layers."""
    from .wikisink import config as wconfig
    from .wikisink import zim as wzim
    from .wikisink import overlay as woverlay
    from .wikisink import save as wsave

    if not wconfig.installed():
        reason = wconfig.unavailable_reason() or (
            "no local wikipedia archive is installed.")
        raise CanonError(
            f"wikisink ingest needs an installed, reachable archive — {reason}")

    # Fuzzy match: prefer suggestion (title-ish), fall back to full-text.
    match_path = None
    try:
        sugg = wzim.suggest(value, limit=5)
        if sugg:
            match_path = sugg[0]["path"]
    except wzim.WikisinkUnavailable:
        pass
    if match_path is None:
        try:
            res = wzim.search(value, 0, 5)
            if res["results"]:
                match_path = res["results"][0]["path"]
        except wzim.WikisinkUnavailable as e:
            raise CanonError(f"wikisink search failed: {e}") from None
    if match_path is None:
        raise CanonError(
            f"no wikipedia article matched {value!r} in the local archive.")

    box = volume_dir(name)
    depth = int(depth)
    written = 0
    seen: set[str] = set()
    # BFS over (path, layer). layer 1 = the matched article.
    queue: deque[tuple[str, int]] = deque([(match_path, 1)])
    while queue:
        path, layer = queue.popleft()
        if path in seen:
            continue
        seen.add(path)
        if len(seen) > INGEST_WIKI_ARTICLE_CAP:
            _set_progress(name, phase="capped", files_written=written,
                          note=f"hit {INGEST_WIKI_ARTICLE_CAP}-article cap")
            break
        try:
            art = woverlay.resolve_article(path=path)
        except (KeyError, wzim.WikisinkUnavailable):
            continue
        try:
            wsave.save_article_to_dir(box, art)
            written += 1
        except Exception as e:  # noqa: BLE001
            log.warning("canon wikisink save skip %s: %s", path, e)
            continue
        _set_progress(name, phase="expanding", files_written=written,
                      articles_seen=len(seen))
        if layer >= depth:
            continue
        for link_path in _wiki_outlinks(art["html"], art["path"]):
            if link_path not in seen:
                queue.append((link_path, layer + 1))
    _set_progress(name, phase="expanding", files_written=written,
                  articles_seen=len(seen))
    return written


def _wiki_outlinks(html: str, article_path: str) -> list[str]:
    """Extract internal ZIM article paths this article links to (same-archive
    crosslinks). Best-effort regex over hrefs; external/anchor/special links
    dropped."""
    import posixpath
    base_dir = posixpath.dirname(article_path)
    out: list[str] = []
    seen: set[str] = set()
    for m in re.finditer(r'href\s*=\s*["\']([^"\']+)["\']', html, re.IGNORECASE):
        href = m.group(1).strip()
        low = href.lower()
        if low.startswith(("http://", "https://", "//", "mailto:",
                           "javascript:", "data:", "#")):
            continue
        target = href.split("#", 1)[0]
        if not target:
            continue
        target = urllib.parse.unquote(target)
        # Skip non-article namespaces (File:, Category:, Special:, etc.).
        tail = target.rsplit("/", 1)[-1]
        if ":" in tail and not tail.startswith("A/"):
            continue
        resolved = posixpath.normpath(posixpath.join(base_dir, target)).lstrip("./")
        if not resolved or resolved in seen:
            continue
        seen.add(resolved)
        out.append(resolved)
    return out


