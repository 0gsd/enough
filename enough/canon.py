def _meta_path(name: str) -> Path:
    return volume_dir(name) / META_NAME


def _default_meta(name: str) -> dict[str, Any]:
    now = _now_iso()
    return {
        "name": name,
        "origin": {"type": "folder", "value": None, "depth": None},
        "status": "complete",     # complete | ingesting | failed
        "created_at": now,
        "updated_at": now,
        "ingest": None,           # progress payload while/after an ingest
        "fingerprint": "",        # cheap content hash for the reconcile check
        "catalog_sha256": "",     # what this module last wrote to canon.cosm
    }


def load_meta(name: str) -> dict[str, Any]:
    """Metadata for a volume, defaulted for any missing key. Reads
    ``.canon.json``, else a pre-0.4.3 ``.cachebox.json``. A volume with
    neither (e.g. a manually-created folder) still returns a sane default so
    callers never handle KeyError."""
    base = _default_meta(name)
    box = volume_dir(name)
    p = box / META_NAME
    if not p.is_file() and (box / LEGACY_META_NAME).is_file():
        p = box / LEGACY_META_NAME
    if p.is_file():
        try:
            on_disk = json.loads(p.read_text(encoding="utf-8"))
            if isinstance(on_disk, dict):
                for k in base:
                    if k in on_disk:
                        base[k] = on_disk[k]
        except (OSError, json.JSONDecodeError) as e:
            log.warning("volume meta read failed for %s (%s); defaulting", name, e)
    base["name"] = name
    return base


def _migrate_meta(box: Path) -> None:
    """``.cachebox.json`` → ``.canon.json``, when only the old one exists."""
    old, new = box / LEGACY_META_NAME, box / META_NAME
    try:
        if old.is_file() and not new.exists():
            os.replace(old, new)
            log.info("canon: %s: renamed %s to %s", box.name, LEGACY_META_NAME, META_NAME)
    except OSError as e:
        log.warning("canon: %s: could not rename %s (%s)", box.name, LEGACY_META_NAME, e)


def save_meta(name: str, meta: dict[str, Any], *, touch: bool = True) -> None:
    """Write a volume's metadata **atomically** (tmp file + os.replace).

    Atomicity is load-bearing, not tidiness. An ingest runs on a worker
    thread that calls this repeatedly while the UI (and the agent, and
    `GET /api/canon/ingest-status`) reads the same file from the request
    thread. With a plain `write_text` — truncate, then write — a concurrent
    reader can catch the file empty or half-written; `load_meta` then hits a
    JSONDecodeError and, by design, falls back to `_default_meta()`, whose
    status is **"complete"**. That is exactly the phantom-complete state
    `run_ingest` promises never to produce: a poller sees "complete" a few
    hundred milliseconds into a copy and walks away with an empty volume.
    `os.replace` is atomic on POSIX and Windows alike, so the reader sees
    either the old JSON or the new one and never a torn one.

    ``touch=False`` keeps ``updated_at`` as it is — for the bookkeeping
    write after a catalog write, which must not change the ``updated`` the
    catalog was just built from.

    The temp file is a dotfile sibling, so the tree scanners, the content
    fingerprint, and `_is_sidecar` all skip it even in the crash window
    where one survives."""
    meta = dict(meta)
    meta["name"] = name
    if touch:
        meta["updated_at"] = _now_iso()
    p = _meta_path(name)
    p.parent.mkdir(parents=True, exist_ok=True)
    _migrate_meta(p.parent)
    tmp = p.with_name(f"{META_NAME}.{os.getpid()}.tmp")
    tmp.write_text(json.dumps(meta, indent=2) + "\n", encoding="utf-8")
    os.replace(tmp, p)


