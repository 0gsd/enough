def emf_twin_path(text: Path) -> Path:
    """`notes.md` → `notes.md.cosm`. Pairing is by name, like convert's
    `twin_path`: the twin's name is the text's whole name plus ``.cosm``."""
    return text.parent / f"{text.name}.cosm"


def _is_emf_twin_of(twin: Path, text: Path) -> bool:
    try:
        if not (twin.is_file() and text.is_file()):
            return False
    except OSError:
        return False
    return macrocosm.sniff_declaration(twin) == EMF_OES


def is_emf_twin(path: Path) -> bool:
    """True iff ``path`` is ``X.cosm`` beside an existing file ``X`` and its
    first lines declare ``oes: emf/1`` (a sniff — no YAML load). A standalone
    EMF (no sibling text) is an ordinary ``.cosm`` file, not a twin."""
    if not path.name.endswith(".cosm") or len(path.name) <= len(".cosm"):
        return False
    return _is_emf_twin_of(path, path.parent / path.name[: -len(".cosm")])


def emf_twins(entries: list[Path]) -> dict[str, Path]:
    """``{text name: twin path}`` for the EMF twins among one folder's
    entries — what listings hide behind their texts."""
    files = set()
    for p in entries:
        try:
            if p.is_file():
                files.add(p.name)
        except OSError:
            continue
    out: dict[str, Path] = {}
    for p in entries:
        n = p.name
        if not n.endswith(".cosm") or len(n) <= len(".cosm") or n not in files:
            continue
        text = n[: -len(".cosm")]
        if text in files and macrocosm.sniff_declaration(p) == EMF_OES:
            out[text] = p
    return out


# A SHORT: a telling compiled from an EMF twin, written beside its text as
# `<text-stem>.short-YYYY-MM-DD-HHMM.md` (`-2`, `-3` on a collision; plan §15,
# `canon_derive.short_path`). It stays an ordinary, visible file — the person's
# to read and edit — and the catalogs only mark it (`short_of`) and its text
# (`shorts`).
SHORT_RE = re.compile(r"^(?P<stem>.+)\.short-(?P<stamp>\d{4}-\d{2}-\d{2}-\d{4})(?:-(?P<n>[1-9][0-9]*))?\.md$")
# The texts enough decompiles (= canon_derive.TEXT_SUFFIXES; a test holds them equal).
SHORT_TEXT_SUFFIXES = (".md", ".markdown", ".mdown", ".mkd", ".txt", ".text")


def short_text_name(name: str, siblings: Any, *, with_emf: Any = (),
                    is_standalone: Callable[[str], bool] | None = None) -> str | None:
    """The file a short named ``name`` is a short of, among the names of the
    files beside it, or None (not a short's name, or its text is not there).
    ``notes.short-2026-10-23-1042.md`` → ``notes.md`` (or ``notes.txt`` …: a
    text whose name less its extension is the stem; one with an EMF twin, in
    ``with_emf``, first, then ``.md``), else ``notes.cosm`` when
    ``is_standalone`` says it is a standalone EMF, else a file named just
    ``notes`` (a converted original: ``report.pdf.short-….md`` is a short of
    ``report.pdf``, read through its ``report.pdf.md``)."""
    m = SHORT_RE.match(name)
    if not m:
        return None
    stem = m.group("stem")
    names = {str(n) for n in siblings} - {name}
    emf = {str(n) for n in with_emf}
    texts = []
    for n in names:
        base, dot, ext = n.rpartition(".")
        if dot and base == stem and f".{ext.lower()}" in SHORT_TEXT_SUFFIXES:
            texts.append((n not in emf, ext.lower() != "md", SHORT_TEXT_SUFFIXES.index(f".{ext.lower()}"), n))
    if texts:
        return min(texts)[-1]
    cosm = f"{stem}.cosm"
    if cosm in names and (is_standalone is None or is_standalone(cosm)):
        return cosm
    return stem if stem in names else None


_TOP_KEY_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_-]*[ \t]*:")


def twin_header(twin: Path, *, max_lines: int = TWIN_HEADER_LINES) -> dict[str, Any]:
    """The top of an EMF twin (everything above ``nodes:``, at most
    ``max_lines`` lines), parsed — enough for its ``source:`` and ``atem:``
    blocks without loading the items. A block cut off by the line cap is
    dropped rather than misread; ``{}`` when nothing parses."""
    lines: list[str] = []
    capped = True
    try:
        with open(twin, encoding="utf-8-sig", errors="replace") as fh:
            for _ in range(max_lines):
                line = fh.readline()
                if not line or line.startswith("nodes:"):
                    capped = False
                    break
                lines.append(line)
    except OSError:
        return {}

    def drop_last_block() -> None:
        for i in range(len(lines) - 1, -1, -1):
            if _TOP_KEY_RE.match(lines[i]):
                del lines[i:]
                return
        lines.clear()

    if capped:
        drop_last_block()
    for _attempt in range(4):
        if not lines:
            return {}
        try:
            data = macrocosm.yaml_load("".join(lines))
        except Exception:  # noqa: BLE001 — yaml errors, impossible dates: drop a block, retry
            drop_last_block()
            continue
        return data if isinstance(data, dict) else {}
    return {}


def emf_state(text: Path, twin: Path, header: dict[str, Any] | None = None) -> str:
    """``fresh`` while the text's size and mtime match the twin's recorded
    ``source`` (or, when they differ, its sha256 still does), else
    ``stale``. Never writes: unlike convert's manifest self-heal, a twin is
    the user's derived text and a listing doesn't touch it."""
    hdr = header if header is not None else twin_header(twin)
    src = hdr.get("source") if isinstance(hdr, dict) else None
    if not isinstance(src, dict):
        return "stale"
    try:
        st = text.stat()
    except OSError:
        return "stale"
    if st.st_size == src.get("size") and st.st_mtime_ns == src.get("mtime_ns"):
        return "fresh"
    want = src.get("sha256")
    if not isinstance(want, str) or not want:
        return "stale"
    try:
        return "fresh" if _sha256_file(text) == want.strip().lower() else "stale"
    except OSError:
        return "stale"


def _atem_line(header: dict[str, Any]) -> str | None:
    atem = header.get("atem") if isinstance(header, dict) else None
    line = atem.get("line") if isinstance(atem, dict) else None
    return line.strip() if isinstance(line, str) and line.strip() else None


def emf_entry(text: Path, rel_twin: str, *, with_state: bool = True,
              twin: Path | None = None) -> dict[str, Any]:
    """The ``emf`` field a listing node or a catalog item carries for a text
    with an EMF twin: ``{path, state}`` (``{path}`` for a project catalog)."""
    tw = twin if twin is not None else emf_twin_path(text)
    out: dict[str, Any] = {"path": rel_twin}
    if with_state:
        out["state"] = emf_state(text, tw)
    return out


def is_holotype_folder(p: Path) -> bool:
    """A folder holding a ``holotype.cosm``: one database of Comprise OES.
    Canon shows it as one folder (badge, opens in the cosm viewer) and never
    enumerates its contents in a catalog."""
    try:
        return p.is_dir() and (p / HOLOTYPE_NAME).is_file()
    except OSError:
        return False


def _is_article_folder(p: Path) -> bool:
    try:
        return p.is_dir() and (p / "article.html").is_file() and (p / ".meta.json").is_file()
    except OSError:
        return False


