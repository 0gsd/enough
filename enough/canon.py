# (new, old) pairs a "both folders exist" warning was already logged for —
# `root()` runs on every tree build, the warning once per process.
_ROOT_WARNED: set[tuple[str, str]] = set()


def migrate_store_folder(new: Path, old: Path) -> str:
    """The one-time move of the store from its old name to its new one.

    ``"renamed"`` when only ``old`` existed and ``os.rename`` moved it (one
    log line); ``"both"`` when both exist — ``new`` is used, a warning names
    both once per process, nothing is merged or deleted; ``"failed"`` when
    the rename raised (the caller keeps using ``old``); ``"none"`` otherwise.
    Never a symlink: a link inside a cloud-synced or two-machine home breaks
    the way the cloud-sync notes describe."""
    try:
        new_there = new.exists() or new.is_symlink()
        old_there = old.is_dir()
    except OSError:
        return "none"
    if new_there:
        if old_there:
            key = (str(new), str(old))
            if key not in _ROOT_WARNED:
                _ROOT_WARNED.add(key)
                log.warning("canon: both %s and %s exist; using %s and leaving %s "
                            "untouched (move anything you still need by hand)",
                            new, old, new, old)
            return "both"
        return "none"
    if not old_there:
        return "none"
    try:
        new.parent.mkdir(parents=True, exist_ok=True)
        os.rename(old, new)
    except OSError as e:
        log.warning("canon: could not rename %s to %s (%s); using the old folder", old, new, e)
        return "failed"
    log.info("canon: renamed the store %s -> %s (Cacheawl is now Canon)", old, new)
    return "renamed"


def root() -> Path:
    """The Canon store root. ``ENOUGH_CANON_ROOT`` when set, else the legacy
    ``ENOUGH_CACHEAWL_ROOT``, else ``~/enough/canon`` — renamed from
    ``~/enough/cacheawl`` on first use when only the old folder exists.
    Created on demand (the store is a flat dir of volumes)."""
    raw = os.environ.get("ENOUGH_CANON_ROOT") or os.environ.get("ENOUGH_CACHEAWL_ROOT")
    if raw:
        p = Path(raw).expanduser()
    else:
        home = Path.home() / "enough"
        p, old = home / "canon", home / "cacheawl"
        if migrate_store_folder(p, old) == "failed":
            p = old
    p.mkdir(parents=True, exist_ok=True)
    return p


def _now_iso() -> str:
    return dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def _validate_name(name: str) -> str:
    name = (name or "").strip()
    if not name:
        raise CanonError("a volume needs a name.")
    if name in (".", ".."):
        raise CanonError(f"{name!r} is not a valid volume name.")
    if not _NAME_RE.match(name):
        raise CanonError(
            f"invalid volume name {name!r} — use letters, digits, spaces, "
            f"hyphens or underscores (must not start with a symbol; 64 chars max)."
        )
    return name


def volume_dir(name: str) -> Path:
    """Absolute path of a volume folder (not required to exist)."""
    return root() / _validate_name(name)


def _is_volume(name: str) -> bool:
    try:
        return volume_dir(name).is_dir()
    except CanonError:
        return False


def require_volume(name: str) -> Path:
    """The folder of an existing volume; `CanonNotFound` otherwise."""
    d = volume_dir(name)
    if not d.is_dir():
        raise CanonNotFound(
            f"no volume named {name!r} in canon. list volumes first (canon_list) "
            f"or create it (canon_create)."
        )
    return d


_require_volume = require_volume


def _slugify(text: str, max_len: int = 40) -> str:
    s = re.sub(r"[^a-zA-Z0-9]+", "-", text).strip("-").lower()
    return (s[:max_len].strip("-")) or "x"


def _sizeof_human(n: int) -> str:
    step = float(n)
    for unit in ("B", "KB", "MB", "GB", "TB"):
        if step < 1024 or unit == "TB":
            return f"{step:.0f} {unit}" if unit == "B" else f"{step:.1f} {unit}"
        step /= 1024
    return f"{n} B"


def _sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest()


def _listing_key(p: Path) -> tuple[bool, str, str]:
    """Folders first, then files, case-folded — the order every Canon listing
    uses — with the exact name as the tie-break so two names that differ only
    in case still sort the same way on every run (catalogs are byte-stable)."""
    try:
        is_dir = p.is_dir()
    except OSError:
        is_dir = False
    return (not is_dir, p.name.lower(), p.name)


def _is_sidecar(p: Path) -> bool:
    """The backend-owned files that never count toward item/size totals and
    never appear as ordinary tree entries: the metadata json (old name too)
    and any dotfile. The catalog IS shown in trees (it opens in the cosm
    viewer) but is excluded from content fingerprints/totals."""
    return p.name in (META_NAME, LEGACY_META_NAME) or p.name.startswith(".")


