_SLUG_BAD = re.compile(r"[^a-z0-9-]")
_RESERVED_SLUGS = frozenset(["con", "prn", "aux", "nul"] + [f"com{i}" for i in range(10)]
                            + [f"lpt{i}" for i in range(10)])

# Serializes catalog writes: a request thread's reconcile, an ingest worker's
# last regenerate and the startup project catalog may meet on one file.
_CATALOG_LOCK = threading.RLock()


def _sha6(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8", "surrogateescape")).hexdigest()[:6]


def slug(text: str) -> str:
    """The Canon slug rule (spec §18.3.3) for one path or name: ``/`` →
    ``--``, ``.`` → ``-``, lowercased, anything outside ``a-z0-9-`` → ``-``,
    a hyphen left at either end trimmed. Collisions are `item_slugs`'s
    business; a Windows reserved name, or nothing left at all, takes the
    ``-<sha6>`` suffix here (the path grammar refuses ``con`` as a segment)."""
    s = _SLUG_BAD.sub("-", text.replace("/", "--").replace(".", "-").lower()).strip("-")
    if not s:
        return _sha6(text)
    if s in _RESERVED_SLUGS:
        return f"{s}-{_sha6(text)}"
    return s


def item_slugs(paths: list[str]) -> dict[str, str]:
    """``{path: slug}`` for every path of one volume: `slug`, and when two
    or more paths would share a slug, **each** of them takes ``-<sha6>`` of
    its own path (spec §18.3.3, P0 decision 13)."""
    base = {p: slug(p) for p in paths}
    seen: dict[str, int] = {}
    for s in base.values():
        seen[s] = seen.get(s, 0) + 1
    return {p: (f"{s}-{_sha6(p)}" if seen[s] > 1 else s) for p, s in base.items()}


def _ts(value: Any) -> Any:
    """A meta timestamp (``2026-10-20T14:02:11Z``) as a datetime, so the
    catalog writes a YAML timestamp; anything else as it is."""
    if isinstance(value, str):
        try:
            return dt.datetime.strptime(value, "%Y-%m-%dT%H:%M:%SZ").replace(tzinfo=dt.timezone.utc)
        except ValueError:
            return value
    return value


def _subtree_counts(folder: Path) -> dict[str, int]:
    """``{folders, files}`` below a folder a catalog lists without its
    contents. Dotfiles and dot-folders are left out; nothing else is
    checked — a count, not an enumeration."""
    folders = files = 0
    for _cur, dirnames, filenames in os.walk(folder, followlinks=False):
        dirnames[:] = [d for d in dirnames if not d.startswith(".")]
        folders += len(dirnames)
        files += sum(1 for f in filenames if not f.startswith("."))
    return {"folders": folders, "files": files}


def _read_article_meta(folder: Path) -> tuple[str | None, str | None]:
    try:
        meta = json.loads((folder / ".meta.json").read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None, None
    if not isinstance(meta, dict):
        return None, None
    title = meta.get("title") if isinstance(meta.get("title"), str) else None
    source = meta.get("source_url") if isinstance(meta.get("source_url"), str) else None
    return title, source


def _enumerate(base: Path, *, skip: Callable[[Path], bool], project: bool,
               cap: int | None = None) -> tuple[list[dict[str, Any]], dict[str, int]]:
    """The ``nodes`` of a canon/1 catalog over ``base`` and its ``counts``.

    Breadth-first, so the shallow structure survives the cap: a folder is
    either listed with all its contents or — once its contents would push
    the catalog past ``cap`` items — listed alone, with ``counts`` and a
    ``pending`` note (the root is always listed). The nodes come out
    depth-first in listing order (folders first, case-folded), each folder's
    ``parts`` in the same order. EMF twins and (via ``skip``) convert twins
    hide behind their originals; a Holotype folder and a saved article
    folder are one item each, never recursed. A project's items carry no
    ``size`` and no twin states (spec §18.3.4)."""
    cap = CATALOG_ITEM_CAP if cap is None else cap
    convert = None
    try:
        from . import convert  # late import: convert is heavy and project-side
    except Exception:  # noqa: BLE001 — a catalog without twin badges beats no catalog
        log.exception("canon: convert unavailable; catalog without markdown twins")

    raw: dict[str, dict[str, Any]] = {}       # rel -> partial item (no id yet)
    children: dict[str, list[str]] = {}       # rel -> child rels, for listed folders
    count = 0
    seen_dirs: set[Path] = set()
    queue: deque[tuple[str, Path]] = deque([("", base)])
    while queue:
        rel, folder = queue.popleft()
        try:
            real = folder.resolve()
        except OSError:
            continue
        if real in seen_dirs:                 # a symlink loop: list it, don't walk it
            children[rel] = []
            continue
        seen_dirs.add(real)
        try:
            entries = sorted(folder.iterdir(), key=_listing_key)
        except OSError:
            children[rel] = []
            continue
        twins = emf_twins(entries)
        hide = {t.name for t in twins.values()}
        shown = [p for p in entries if p.name not in hide and not skip(p)]
        if rel and count + len(shown) > cap:
            raw[rel]["counts"] = _subtree_counts(folder)
            raw[rel]["pending"] = CATALOG_PENDING
            continue
        kids: list[str] = []
        for p in shown:
            crel = f"{rel}/{p.name}" if rel else p.name
            it: dict[str, Any] = {"name": p.name, "path": crel, "parent": rel or None}
            try:
                is_dir = p.is_dir()
            except OSError:
                is_dir = False
            if is_dir and is_holotype_folder(p):
                it["type"] = "folder"
                it["holotype"] = True
            elif is_dir and _is_article_folder(p):
                title, source = _read_article_meta(p)
                it["type"] = "article"
                it["title"] = title or p.name
                if source:
                    it["source"] = source
            elif is_dir:
                it["type"] = "folder"
                queue.append((crel, p))
            else:
                it["type"] = "file"
                if not project:
                    try:
                        it["size"] = p.stat().st_size
                    except OSError:
                        it["size"] = 0
                it["kind"] = file_kind(p)
                if convert is not None and convert.is_convertible(p) and convert.has_twin(p):
                    twin: dict[str, Any] = {"path": f"{crel}.md"}
                    if not project:
                        try:
                            twin["state"] = convert.state(p)
                        except Exception:  # noqa: BLE001 — a state is a badge, not a reason to fail
                            twin["state"] = "stale"
                    it["twin"] = twin
                tw = twins.get(p.name)
                if tw is not None:
                    hdr = twin_header(tw)
                    emf: dict[str, Any] = {"path": f"{rel}/{tw.name}" if rel else tw.name}
                    if not project:
                        emf["state"] = emf_state(p, tw, hdr)
                    it["emf"] = emf
                    line = _atem_line(hdr)
                    if line:
                        it["atem"] = {"line": line}
            raw[crel] = it
            kids.append(crel)
            count += 1
        children[rel] = kids
        # Shorts (plan §15): a `<stem>.short-<stamp>.md` beside its text is
        # marked `short_of: <text>`, and the text `shorts: [<short> …]`, in
        # listing order (so, by date). Both are paths: structure only.
        files = {raw[k]["name"]: k for k in kids if raw[k]["type"] == "file"}
        for k in kids:
            it = raw[k]
            if it["type"] != "file" or not SHORT_RE.match(it["name"]):
                continue
            text = short_text_name(
                it["name"], files, with_emf=twins,
                is_standalone=lambda n, folder=folder: macrocosm.sniff_declaration(folder / n) == EMF_OES)
            if text is not None:
                it["short_of"] = files[text]
                raw[files[text]].setdefault("shorts", []).append(k)

    order: list[str] = []

    def walk(rel: str) -> None:
        for c in children.get(rel, []):
            order.append(c)
            if c in children and raw[c]["type"] == "folder":
                walk(c)

    walk("")
    slugs = item_slugs(order)
    ids = {rel: f"V:{raw[rel]['type']}/{slugs[rel]}" for rel in order}
    nodes: list[dict[str, Any]] = []
    counts = {"folders": 0, "files": 0, "articles": 0, "twins": 0, "atems": 0}
    for rel in order:
        it = raw[rel]
        node: dict[str, Any] = {"id": ids[rel], "type": it["type"], "name": it["name"], "path": rel}
        if it["parent"]:
            node["parent"] = ids[it["parent"]]
        for key in ("holotype", "size", "kind", "twin", "emf", "atem", "short_of", "shorts", "title", "source"):
            if key in it:
                node[key] = it[key]
        if it["type"] == "folder" and not it.get("holotype"):
            if rel in children:
                node["parts"] = [ids[c] for c in children[rel]]
            if "counts" in it:
                node["counts"] = it["counts"]
                node["pending"] = it["pending"]
        nodes.append(node)
        counts[{"folder": "folders", "file": "files", "article": "articles"}[it["type"]]] += 1
        if "emf" in it:
            counts["twins"] += 1
        if "atem" in it:
            counts["atems"] += 1
    return nodes, counts


def _catalog_skip(box: Path) -> Callable[[Path], bool]:
    """What a volume's catalog leaves out (EMF twins are handled by the
    enumeration itself): dotfiles, the metadata, the old mirror, the catalog,
    and convert twins with their asset folders, which appear as ``twin:`` on
    their originals (the project tree's rule)."""
    catalog = box / CATALOG_NAME

    def skip(p: Path) -> bool:
        if p.name.startswith(".") or p.name in (LEGACY_MIRROR_NAME, META_NAME, LEGACY_META_NAME):
            return True
        if p == catalog:
            return True
        try:
            from . import convert
        except Exception:  # noqa: BLE001
            return False
        if p.name.endswith(".assets") and p.is_dir():
            return convert.has_twin(p.parent / p.name[: -len(".assets")])
        if p.name.endswith(".md"):
            return convert.has_twin(p.parent / p.name[: -len(".md")])
        return False

    return skip


def _volume_catalog(name: str, meta: dict[str, Any], box: Path) -> dict[str, Any]:
    nodes, counts = _enumerate(box, skip=_catalog_skip(box), project=False)
    origin = {k: v for k, v in (meta.get("origin") or {}).items()
              if k in ("type", "value", "depth") and v not in (None, "")}
    cat: dict[str, Any] = {
        "oes": OES,
        "macrocosm": macrocosm.MACROCOSM_VERSION,
        "id": f"canon/{slug(name)}",
        "name": name,
        "scope": "volume",
    }
    if origin:
        cat["origin"] = origin
    cat["status"] = meta.get("status") or "complete"
    if meta.get("created_at"):
        cat["created"] = _ts(meta["created_at"])
    if meta.get("updated_at"):
        cat["updated"] = _ts(meta["updated_at"])
    cat["counts"] = counts
    cat["nodes"] = nodes
    return cat


def build_catalog(name: str) -> str:
    """The text of a volume's ``canon.cosm`` as it would be written now.
    Pure: never writes (`regenerate_catalog` does)."""
    box = _require_volume(name)
    return macrocosm.dump(_volume_catalog(name, load_meta(name), box))


def _write_if_changed(path: Path, text: str) -> bool:
    """Write ``text`` to ``path`` atomically (dotfile tmp + os.replace) and
    only when the bytes differ. True when it wrote."""
    data = text.encode("utf-8")
    try:
        if path.read_bytes() == data:
            return False
    except OSError:
        pass
    tmp = path.with_name(f".{path.name}.{os.getpid()}.{threading.get_ident()}.tmp")
    tmp.write_bytes(data)
    os.replace(tmp, path)
    return True


def regenerate_catalog(name: str) -> Path:
    """(Re)write ``canon.cosm`` from the volume's current contents and
    metadata. Called after every backend mutation and on reconcile drift.

    Order matters for byte-stability: the fingerprint is refreshed first
    (which stamps ``updated_at`` only when the content really moved), the
    catalog is built from that metadata and written only if its bytes
    differ, and the catalog's sha is recorded without touching
    ``updated_at`` — so a rerun over an unchanged volume writes nothing."""
    with _CATALOG_LOCK:
        box = volume_dir(name)
        box.mkdir(parents=True, exist_ok=True)
        _migrate_sidecars(box)
        meta = load_meta(name)
        current = _fingerprint(box)
        if current != meta.get("fingerprint") or not (box / META_NAME).is_file():
            meta["fingerprint"] = current
            save_meta(name, meta)
            meta = load_meta(name)
        text = macrocosm.dump(_volume_catalog(name, meta, box))
        path = box / CATALOG_NAME
        _write_if_changed(path, text)
        sha = hashlib.sha256(text.encode("utf-8")).hexdigest()
        if meta.get("catalog_sha256") != sha:
            meta["catalog_sha256"] = sha
            save_meta(name, meta, touch=False)
        return path


def _catalog_current(box: Path, meta: dict[str, Any]) -> bool:
    """Is ``canon.cosm`` there and exactly what this module last wrote? A
    catalog edited or deleted by another program is rewritten at the next
    reconcile (spec §18.3: only enough writes it)."""
    try:
        data = (box / CATALOG_NAME).read_bytes()
    except OSError:
        return False
    return hashlib.sha256(data).hexdigest() == meta.get("catalog_sha256")


def project_catalog(project_dir: Path, *, write: bool = True) -> str:
    """The project's canon/1 catalog (``rness/canon.cosm``, plan §6.7):
    exactly what the sidebar shows — `home._mirror_skip`'s rules — minus
    ``rness/``; ``scope: project``; structure only (no ``size``, no
    ``mtime``, no timestamps, ``twin``/``emf`` as ``{path}``), so the bytes
    change only when files are added, removed or renamed, or twins and atems
    change. Built in memory; with ``write`` it is written (tmp +
    ``os.replace``) only when the bytes differ, and only into an existing
    ``rness/``. Returns the text.

    Called at project open, from the Canon tree route, from the cosm routes
    on ``rness/canon.cosm`` and from ``GET /api/canon/project-catalog`` —
    never from ``/api/files`` or a tree build."""
    from . import home as _home
    from . import project_meta as _project_meta

    project_dir = Path(project_dir)
    visible = _home._mirror_skip(project_dir)
    rness = project_dir / "rness"

    def skip(p: Path) -> bool:
        if p.parent == project_dir and p.name == "rness":
            return True
        return visible(p)

    name = str(_project_meta.load(project_dir).get("name") or project_dir.name)
    nodes, counts = _enumerate(project_dir, skip=skip, project=True)
    text = macrocosm.dump({
        "oes": OES,
        "macrocosm": macrocosm.MACROCOSM_VERSION,
        "id": f"canon/~{slug(name)}",
        "name": name,
        "scope": "project",
        "counts": counts,
        "nodes": nodes,
    })
    if write and rness.is_dir():
        with _CATALOG_LOCK:
            try:
                if _write_if_changed(project_dir / PROJECT_CATALOG, text):
                    log.info("canon: wrote %s", project_dir / PROJECT_CATALOG)
            except OSError as e:
                log.warning("canon: could not write %s (%s)", project_dir / PROJECT_CATALOG, e)
    return text


