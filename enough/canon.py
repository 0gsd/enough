def _scan_tree(box: Path, rel_parts: tuple[str, ...] = ()) -> list[dict[str, Any]]:
    """Nested tree of a volume for the UI icon grid. Folders first, then
    files, each alphabetical. Dotfiles + the metadata json are omitted.

    Flags (plan §6.3): the root ``canon.cosm`` is ``catalog: true``; any
    other ``*.cosm`` is ``cosm: true``; an EMF twin is hidden behind its text,
    which carries ``emf: {path, state}``; a folder holding ``holotype.cosm``
    is ``holotype: true`` and not recursed (it opens in the cosm viewer); a
    saved wikisink ``article.html`` is ``wiki_article``. ``is_mirror`` is on
    every node and always false — the mirror is no longer a file — kept for
    one release so older UI code reads a boolean."""
    here = box.joinpath(*rel_parts)
    try:
        entries = sorted(
            here.iterdir(), key=lambda p: (not p.is_dir(), p.name.lower())
        )
    except OSError:
        return []
    twins = emf_twins(entries)
    hidden = {t.name for t in twins.values()}
    out: list[dict[str, Any]] = []
    for p in entries:
        if p.name.startswith(".") or p.name in hidden:
            continue
        rel = "/".join(rel_parts + (p.name,))
        node: dict[str, Any] = {
            "name": p.name,
            "path": rel,
            "is_dir": p.is_dir(),
            "is_mirror": False,
        }
        if p.is_dir():
            if is_holotype_folder(p):
                node["holotype"] = True
                node["children"] = []
            else:
                node["children"] = _scan_tree(box, rel_parts + (p.name,))
        else:
            try:
                node["size"] = p.stat().st_size
            except OSError:
                node["size"] = 0
            if not rel_parts and p.name == CATALOG_NAME:
                node["catalog"] = True
            elif p.suffix == ".cosm":
                node["cosm"] = True
            elif p.name == "article.html":
                # Saved wikisink article (folder shape: article.html +
                # .meta.json sidecar) — the UI routes these into the
                # wikisink reader, not the raw-text editor.
                try:
                    if (p.parent / ".meta.json").is_file():
                        node["wiki_article"] = True
                except OSError:
                    pass
            twin = twins.get(p.name)
            if twin is not None:
                node["emf"] = emf_entry(p, "/".join(rel_parts + (twin.name,)), twin=twin)
        out.append(node)
    return out


def _content_files(box: Path) -> list[Path]:
    """Every real content file in the volume (recursive), excluding the
    catalog at its root, the old mirror, the metadata json, and any
    dotfile. EMF twins count: they are the user's derived text."""
    out: list[Path] = []
    for p in sorted(box.rglob("*")):
        if not p.is_file():
            continue
        rel = p.relative_to(box)
        if p.name in (LEGACY_MIRROR_NAME, META_NAME, LEGACY_META_NAME):
            continue
        if rel.as_posix() == CATALOG_NAME:
            continue
        if any(part.startswith(".") for part in rel.parts):
            continue
        out.append(p)
    return out


def _stats(box: Path) -> dict[str, int]:
    files = _content_files(box)
    total = 0
    for f in files:
        try:
            total += f.stat().st_size
        except OSError:
            pass
    dirs = {p for p in box.rglob("*") if p.is_dir()}
    return {"item_count": len(files), "dir_count": len(dirs),
            "total_size": total}


def _fingerprint(box: Path) -> str:
    """Cheap content fingerprint: (relpath, size, mtime-int) of every content
    file, hashed. Changes whenever a file is added/removed/edited — the
    reconcile check compares this against the value stored in metadata to
    catch manual drops the backend didn't perform."""
    h = hashlib.sha256()
    for f in _content_files(box):
        try:
            st = f.stat()
        except OSError:
            continue
        rel = f.relative_to(box).as_posix()
        h.update(f"{rel}\0{st.st_size}\0{int(st.st_mtime)}\n".encode("utf-8", "ignore"))
    return h.hexdigest()[:16]


