def _resolve_endpoint(project_dir: Path, kind: str, box: str | None,
                      rel: str) -> tuple[Path, Path]:
    """Resolve one side of a transfer to (base_root, absolute_target),
    verifying containment. ``kind`` is 'project' or 'canon' (the legacy
    'cachebox' is accepted). Raises `CanonError` on traversal escape or a bad
    volume.

    Containment is checked against the resolved base — the /var vs
    /private/var discipline — so a symlinked temp root on macOS still
    passes."""
    rel = (rel or "").strip().lstrip("/")
    if kind == "project":
        base = project_dir
    elif kind in VOLUME_KINDS:
        if not box:
            raise CanonError("a canon endpoint needs a <box> (the volume's name).")
        base = _require_volume(box)
    else:
        raise CanonError(
            f"unknown transfer endpoint kind {kind!r} — use 'project' or "
            f"'canon'."
        )
    if ".." in Path(rel).parts:
        raise CanonError(f"path {rel!r} contains a '..' traversal component.")
    base_real = base.resolve(strict=False)
    target = (base_real / rel).resolve(strict=False)
    try:
        target.relative_to(base_real)
    except ValueError:
        raise CanonError(
            f"path {rel!r} escapes its {kind} root — refused."
        ) from None
    return base_real, target


def _guard_transfer_file(project_dir: Path, target: Path, *, is_dst: bool) -> None:
    """Refuse to move/overwrite the files enough keeps via transfer."""
    if target.name in (META_NAME, LEGACY_META_NAME, LEGACY_MIRROR_NAME) or \
            is_catalog_file(target, project_dir):
        raise CanonError(
            f"{target.name} is kept by enough — it can't be a transfer "
            f"{'destination' if is_dst else 'source'}. transfer the volume's "
            f"real content files instead."
        )


def _affected_volume(kind: str, box: str | None) -> str | None:
    return box if kind in VOLUME_KINDS else None


def _private_refusal(what: str) -> str:
    return (f"{what} is a Holotype's private part (its people files, database, "
            f"feeds, scans, bindings, reports or snapshots) — those never leave "
            f"Comprise, so Canon doesn't take a copy. move the rest of the "
            f"Holotype instead.")


def transfer(project_dir: Path, *, op: str,
             src_kind: str, src_box: str | None, src_path: str,
             dst_kind: str, dst_box: str | None, dst_path: str,
             overwrite: bool = False) -> dict[str, Any]:
    """Copy or move a file/folder between the project dir and a volume
    (either direction) or within/between volumes. A side's kind is
    ``"project"`` or ``"canon"`` (legacy ``"cachebox"`` accepted).

    ``dst_path`` names the destination path (including the final name). If
    it names an existing directory, the source is placed inside it under
    its own name. Refuses to clobber unless ``overwrite`` is set. Catalogs
    are regenerated for every volume the op touches.

    Into the store, a Holotype keeps its private parts (`HolotypeFilter`,
    the ingest's rule): whenever the source is, is inside, or contains a
    folder holding ``holotype.cosm``, its people files, database and
    private folders are left out and listed in ``skipped`` (paths relative
    to the source's root; folders end in ``/``). A lone private file or
    folder is refused. A *move* that would leave private parts behind
    copies the filtered set instead and leaves the source whole — nothing
    of a Holotype is ever deleted by a transfer — and says so in ``note``
    (``source_kept: true``).
    """
    if op not in ("copy", "move"):
        raise CanonError(f"transfer op must be 'copy' or 'move', got {op!r}.")

    _sbase, src = _resolve_endpoint(project_dir, src_kind, src_box, src_path)
    if not src.exists():
        raise CanonError(f"transfer source does not exist: {src_path!r}.")
    _guard_transfer_file(project_dir, src, is_dst=False)

    dbase, dst = _resolve_endpoint(project_dir, dst_kind, dst_box, dst_path)
    # Into the store a Holotype's private parts stay behind. Decided before
    # anything is written or removed: a lone private source is refused, and a
    # move that would leave private parts behind becomes a filtered copy.
    holotype = HolotypeFilter(_sbase) if dst_kind in VOLUME_KINDS else None
    if holotype is not None and holotype.private(src):
        raise CanonError(_private_refusal(src_path or src.name))
    skipped: list[Path] = []
    source_kept = bool(holotype is not None and op == "move" and src.is_dir()
                       and holotype.skipped_under(src))
    # If dst is an existing dir, drop the source into it under its own name.
    if dst.exists() and dst.is_dir():
        dst = (dst / src.name).resolve(strict=False)
        try:
            dst.relative_to(dbase)
        except ValueError:
            raise CanonError("resolved destination escaped its root.") from None
    _guard_transfer_file(project_dir, dst, is_dst=True)

    if src.resolve() == dst.resolve():
        raise CanonError("source and destination are the same path.")
    if dst.exists() and not overwrite:
        raise CanonError(
            f"destination already exists: {dst.name}. pass overwrite to "
            f"replace it, or choose a different name."
        )
    if dst.exists() and overwrite:
        if dst.is_dir():
            shutil.rmtree(dst)
        else:
            dst.unlink()

    dst.parent.mkdir(parents=True, exist_ok=True)
    if op == "copy" or source_kept:
        if src.is_dir():
            shutil.copytree(src, dst, symlinks=False,
                            ignore=holotype.ignore_for(skipped) if holotype else None)
        else:
            shutil.copy2(src, dst)
    else:  # move
        shutil.move(str(src), str(dst))

    # Regenerate catalogs for any volume involved.
    touched = {b for b in (_affected_volume(src_kind, src_box),
                           _affected_volume(dst_kind, dst_box)) if b}
    for b in touched:
        if _is_volume(b):
            regenerate_catalog(b)

    out: dict[str, Any] = {
        "op": op,
        "src": {"kind": src_kind, "box": src_box, "path": src_path},
        "dst": {"kind": dst_kind, "box": dst_box,
                "path": str(dst.relative_to(dbase))},
        "boxes_updated": sorted(touched),
        "volumes_updated": sorted(touched),
        "skipped": [q.relative_to(_sbase).as_posix() + ("/" if q.is_dir() else "")
                    for q in skipped],
    }
    if source_kept:
        out["source_kept"] = True
        out["note"] = (
            f"moved as a copy: {len(skipped)} private part(s) of the Holotype "
            f"(listed in skipped) stayed at the source, which was left intact — "
            f"people files and Comprise's private stores never leave Comprise.")
    return out


# ---------------------------------------------------------------------------
# Reconcile — the freshness check the listing endpoint triggers
# ---------------------------------------------------------------------------

def reconcile(name: str) -> bool:
    """Cheaply detect manual file drops the backend didn't see (fingerprint
    drift), a missing catalog, or a catalog another program changed, and
    regenerate the catalog then. Returns True iff it was regenerated. The
    first reconcile of a pre-0.4.3 volume also renames its metadata and
    removes its old persisted mirror."""
    box = volume_dir(name)
    if not box.is_dir():
        return False
    with _CATALOG_LOCK:
        _migrate_sidecars(box)
        meta = load_meta(name)
        # Don't fight an in-flight ingest — it owns the catalog while running.
        if meta.get("status") == "ingesting":
            return False
        current = _fingerprint(box)
        if current != meta.get("fingerprint") or not _catalog_current(box, meta):
            regenerate_catalog(name)
            return True
        return False


def reconcile_all() -> list[str]:
    """Reconcile every volume; return the names that were regenerated."""
    changed = []
    for summary in list_volumes():
        try:
            if reconcile(summary["name"]):
                changed.append(summary["name"])
        except CanonError:
            continue
    return changed


