def _node_id(rel: str) -> str:
    """Stable mermaid node id derived from a relative path — deterministic
    so diffs between regenerations stay readable. The short hash keeps two
    different paths that slugify identically from colliding."""
    if rel == "":
        return "root"
    slug = _slugify(rel, max_len=40)
    digest = hashlib.sha256(rel.encode("utf-8", "ignore")).hexdigest()[:6]
    return f"n_{slug}_{digest}"


def _mm_label(text: str) -> str:
    """Neutralize characters that would break a quoted mermaid node label."""
    return (text.replace("\\", "／").replace('"', "'")
            .replace("[", "(").replace("]", ")")
            .replace("{", "(").replace("}", ")")
            .replace("\n", " ").strip())


def _safe_subrel(box: Path, subpath: str) -> tuple[str, ...]:
    """Validate a volume-relative subfolder path and return its parts.
    ``""`` (or ``/``) → the volume root (empty tuple). Rejects absolute
    paths, ``..`` components, and anything resolving outside the volume, and
    requires the target to be an existing directory. Raises `CanonError`
    otherwise — the same traversal discipline the transfer/`canon:` scheme
    apply."""
    sub = (subpath or "").strip().strip("/")
    if not sub:
        return ()
    p = Path(sub)
    if p.is_absolute() or ".." in p.parts:
        raise CanonError(f"invalid subpath: {subpath!r}")
    target = box / p
    try:
        target.resolve(strict=False).relative_to(box.resolve(strict=False))
    except ValueError:
        raise CanonError(f"subpath escapes the volume: {subpath!r}") from None
    if not target.is_dir():
        raise CanonNotFound(f"no such folder in the volume: {subpath!r}")
    return p.parts


def folder_flowchart(
    base: Path,
    root_label: str,
    *,
    start: tuple[str, ...] = (),
    meta_lines: list[str] | None = None,
    skip: Callable[[Path], bool] | None = None,
    max_depth: int = MIRROR_MAX_DEPTH,
) -> tuple[str, dict[str, dict[str, Any]]]:
    """A Mermaid ``flowchart TD`` mirroring a folder tree. **Shared** — the
    volume mirrors below and the home screen's project mirrors
    (``home.build_project_mirror``) are the same diagram with different
    labels, so they are the same code.

    - ``base`` roots the relative paths and node ids; ``start`` is the
      subtree to actually draw (``()`` = all of ``base``).
    - ``root_label`` and ``meta_lines`` are raw text — escaping is ours.
      ``meta_lines`` of ``None`` omits the ``🛈`` node entirely.
    - ``skip(p)`` hides an entry from the diagram; the depth-cap's
      "… N items" node counts exactly the files that were *not* skipped.

    Returns ``(body, node_map)`` where ``node_map`` is ``{node_id: {"path":
    <base-relative path>, "is_dir": bool}}`` — the viewer's shift-click menu
    resolves a rendered node back to its on-disk location through it.
    """
    lines = ["flowchart TD"]
    edges: list[str] = []
    node_map: dict[str, dict[str, Any]] = {}
    hidden = skip or (lambda _p: False)

    root_id = "root"
    lines.append(f'  {root_id}["{_mm_label(root_label)}"]')
    node_map[root_id] = {"path": "/".join(start), "is_dir": True}

    if meta_lines:
        lines.append(f'  meta["🛈 {_mm_label("<br/>".join(meta_lines))}"]')
        edges.append(f"  {root_id} -.-> meta")

    def walk(rel_parts: tuple[str, ...], parent_id: str, level: int) -> None:
        here = base.joinpath(*rel_parts)
        try:
            entries = sorted(
                here.iterdir(), key=lambda p: (not p.is_dir(), p.name.lower())
            )
        except OSError:
            return
        entries = [e for e in entries if not hidden(e)]
        # Depth cap: collapse everything below the cap into one count node.
        if level >= max_depth and entries:
            descendants = [p for p in here.rglob("*") if p.is_file() and not hidden(p)]
            cid = _node_id("/".join(rel_parts) + "/…")
            lines.append(f'  {cid}["… {len(descendants)} items"]')
            edges.append(f"  {parent_id} --> {cid}")
            # The collapse node stands in for its (uncollapsed) folder.
            node_map[cid] = {"path": "/".join(rel_parts), "is_dir": True}
            return
        for e in entries:
            rel = "/".join(rel_parts + (e.name,))
            nid = _node_id(rel)
            node_map[nid] = {"path": rel, "is_dir": e.is_dir()}
            if e.is_dir():
                lines.append(f'  {nid}["📁 {_mm_label(e.name)}"]')
                edges.append(f"  {parent_id} --> {nid}")
                walk(rel_parts + (e.name,), nid, level + 1)
            else:
                lines.append(f'  {nid}["📄 {_mm_label(e.name)}"]')
                edges.append(f"  {parent_id} --> {nid}")

    walk(start, root_id, 0)
    return "\n".join(lines + edges) + "\n", node_map


def _volume_skip(box: Path) -> Callable[[Path], bool]:
    """What a volume mirror never draws: its metadata (either name), the old
    mirror file, its catalog, any dotfile (the same set `_content_files`
    calls "not content", minus EMF twins), and EMF twins, which hide behind
    their texts as they do in the grid."""
    catalog = box / CATALOG_NAME

    def skip(p: Path) -> bool:
        if p.name in (META_NAME, LEGACY_META_NAME, LEGACY_MIRROR_NAME) or p.name.startswith("."):
            return True
        if p == catalog:
            return True
        return p.suffix == ".cosm" and is_emf_twin(p)

    return skip


def _mirror_body(name: str, meta: dict[str, Any], box: Path,
                 subpath: str = "") -> tuple[str, dict[str, dict[str, Any]]]:
    """The Mermaid ``flowchart TD`` for a volume (``subpath=""``) or a
    subfolder within it: a root node, folder and file nodes mirroring the
    tree (depth-capped), and a metadata node.

    Node/edge generation is `folder_flowchart`; what's volume-specific is
    the two labels."""
    subrel = _safe_subrel(box, subpath)
    base = box.joinpath(*subrel)
    stats = _stats(base)

    root_label = f"📁 {subrel[-1]}" if subrel else f"📦 {name}"

    # Metadata node — full origin for a volume root; a lighter folder header
    # for a subfolder (origin is volume-level, not per-folder).
    if subrel:
        meta_lines = [
            f"folder: {'/'.join(subrel)}",
            f"in volume: {name}",
            f"items: {stats['item_count']} · size: {_sizeof_human(stats['total_size'])}",
        ]
    else:
        origin = meta.get("origin") or {}
        otype = origin.get("type") or "folder"
        oval = origin.get("value")
        odepth = origin.get("depth")
        origin_str = otype
        if oval:
            origin_str += f": {oval}"
        if odepth not in (None, ""):
            origin_str += f" (depth {odepth})"
        meta_lines = [
            f"origin: {origin_str}",
            f"status: {meta.get('status', 'complete')}",
            f"items: {stats['item_count']} · size: {_sizeof_human(stats['total_size'])}",
            f"created: {meta.get('created_at', '?')}",
            f"updated: {meta.get('updated_at', '?')}",
        ]
    return folder_flowchart(box, root_label, start=subrel,
                            meta_lines=meta_lines, skip=_volume_skip(box))


def _mirror_frontmatter(name: str, subpath: str = "") -> str:
    """The ``---`` frontmatter block for a mirror. Volume root vs a
    subfolder differ only in ``title`` and ``source``."""
    sub = (subpath or "").strip().strip("/")
    if sub:
        title = f"folder: {sub} — volume: {name}"
        source = f"canon:{name}/{sub}"
    else:
        title = f"volume: {name}"
        source = f"canon:{name}"
    fm = [
        "---",
        "merirmaid: 1",
        f"title: {title}",
        "modality: mirror",
        "node-char-limit: 48",
        f"source: {source}",
        f"generated: {_now_iso()}",
        "---",
    ]
    return "\n".join(fm) + "\n"


def build_mirror(name: str, subpath: str = "") -> tuple[str, dict[str, dict[str, Any]]]:
    """Return ``(merirmaid_text, node_map)`` for a volume (``subpath=""``)
    or a subfolder within it. Pure generation — **never writes**: since
    0.4.3 no mirror is persisted, the volume root's included (the catalog,
    ``canon.cosm``, is the volume's file of record). Raises `CanonError`
    for a missing volume or an invalid subpath (`CanonNotFound` for one
    that isn't there)."""
    box = _require_volume(name)
    meta = load_meta(name)
    body, node_map = _mirror_body(name, meta, box, subpath)
    return _mirror_frontmatter(name, subpath) + body, node_map


def _is_mirror_text(path: Path) -> bool:
    """Does this ``.merirmaid`` file open with frontmatter saying
    ``modality: mirror``? Reads the first 600 characters only."""
    try:
        head = path.read_text(encoding="utf-8", errors="ignore")[:600]
    except OSError:
        return False
    lines = head.splitlines()
    if not lines or lines[0].strip() != "---":
        return False
    # Scan the frontmatter block only (up to the closing fence).
    for line in lines[1:]:
        if line.strip() == "---":
            break
        if re.match(r"\s*modality:\s*mirror\b", line):
            return True
    return False


def _migrate_sidecars(box: Path) -> None:
    """A volume's first reconcile under 0.4.3: rename the old metadata, and
    delete the old persisted mirror when it is one (a file of that name that
    is not a generated mirror is somebody's and stays)."""
    _migrate_meta(box)
    old = box / LEGACY_MIRROR_NAME
    try:
        if old.is_file() and _is_mirror_text(old):
            old.unlink()
            log.info("canon: %s: removed the old persisted mirror %s (mirrors are drawn "
                     "on demand now; the catalog is %s)", box.name, LEGACY_MIRROR_NAME, CATALOG_NAME)
    except OSError as e:
        log.warning("canon: %s: could not remove %s (%s)", box.name, LEGACY_MIRROR_NAME, e)


